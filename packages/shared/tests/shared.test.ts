import { describe, expect, it } from "vitest";
import {
  buildCardHtml,
  detectLanguage,
  encodePreset,
  decodePreset,
  normalizeConfig,
  cardConfigSchema,
  THEMES,
  FONTS,
  MAX_CODE_BYTES,
} from "../src/index.js";
import { configHash } from "../src/hash.js";

describe("detectLanguage", () => {
  it("detects common languages", () => {
    expect(detectLanguage("def foo():\n    return 1")).toBe("python");
    expect(detectLanguage("package main\nfunc main() { x := 1 }")).toBe("go");
    expect(detectLanguage("const x = 1;\nconsole.log(x);")).toBe("javascript");
    expect(detectLanguage("SELECT * FROM users WHERE id = 1;")).toBe("sql");
    expect(detectLanguage("#include <stdio.h>\nint main(){}")).toBe("cpp");
  });
});

describe("config", () => {
  it("applies defaults", () => {
    const c = normalizeConfig({ code: "x" });
    expect(c.theme).toBe("github-dark");
    expect(c.watermark).toBe(true);
    expect(c.language).toBe("auto");
  });

  it("rejects code over 50 KB", () => {
    expect(cardConfigSchema.safeParse({ code: "x".repeat(MAX_CODE_BYTES + 1) }).success).toBe(false);
  });

  it("hash is stable across key order and defaults", () => {
    expect(configHash({ code: "x", theme: "nord" })).toBe(configHash({ theme: "nord", code: "x" }));
    expect(configHash({ code: "x" })).toBe(configHash({ code: "x", padding: 48 }));
    expect(configHash({ code: "x" })).not.toBe(configHash({ code: "y" }));
  });

  it("round-trips through the URL preset", () => {
    const c = normalizeConfig({ code: "console.log(1)", title: "a.ts", highlightLines: [1, 2], background: { type: "solid", color: "#123456" } });
    expect(decodePreset(encodePreset(c))).toEqual(c);
    expect(decodePreset("!!!")).toBeNull();
  });

  it("ships >= 15 themes and >= 6 fonts", () => {
    expect(THEMES.length).toBeGreaterThanOrEqual(15);
    expect(FONTS.length).toBeGreaterThanOrEqual(6);
  });
});

describe("buildCardHtml", () => {
  it("renders highlighted code, line numbers and the watermark", async () => {
    const html = await buildCardHtml(
      normalizeConfig({ code: "let a = 1;\nlet b = 2;", highlightLines: [1], title: "x.ts" }),
    );
    expect(html).toContain("class=\"line hl\"");
    expect(html).toContain("counter(line)");
    expect(html).toContain("Generated by Code2Img");
    expect(html).toContain("x.ts");
    expect(html).not.toContain("<script");
  });

  it("respects ratio dimensions and transparent background", async () => {
    const html = await buildCardHtml(normalizeConfig({ code: "x", ratio: "og" }));
    expect(html).toContain("width:1200px;height:630px");
    const t = await buildCardHtml(normalizeConfig({ code: "x", background: { type: "transparent" } }));
    expect(t).toContain("transparent");
  });

  it("falls back on unknown language/theme without throwing", async () => {
    const html = await buildCardHtml(normalizeConfig({ code: "x", language: "notalang", theme: "nope" }));
    expect(html).toContain("#capture");
  });
});
